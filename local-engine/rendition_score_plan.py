def _bounded_number(value, low, high):
    return type(value) in (float, int) and math.isfinite(value) and low <= value <= high


def _compact(analysis):
    phrases = analysis.get("phrases") or []
    if not isinstance(phrases, list):
        raise ValueError("The recording analysis needs a list of source phrases.")
    indices = sorted({round(i * (len(phrases) - 1) / 5) for i in range(6)}) if phrases else []
    summary = {k: analysis[k] for k in ("bpm", "meter", "key", "tonic", "mode", "durationSeconds")
               if k in analysis and isinstance(analysis[k], (str, int, float)) and len(str(analysis[k])) <= 80}
    for k in ("chords", "chordSummary", "harmony"):
        value = analysis.get(k)
        if isinstance(value, str):
            summary[k] = value[:240]
        elif isinstance(value, list):
            summary[k] = [v for v in value[:12] if isinstance(v, str) and len(v) <= 40]
    summary["phraseCount"] = len(phrases)
    summary["phrases"] = []
    for i in indices:
        phrase = phrases[i]
        if isinstance(phrase, dict):
            info = {k: v for k, v in phrase.items() if isinstance(v, (float, int, str)) and len(str(v)) <= 70}
            for k in ("pitches", "openingPitches", "contour", "anchorPitches"):
                if isinstance(phrase.get(k), list):
                    info[k] = [v for v in phrase[k][:8] if type(v) in (int, float)]
            summary["phrases"].append({"index": i, **info})
    return summary


def _anchors(analysis):
    count = analysis.get("_phraseCount", len(analysis.get("phrases") or []))
    explicit = analysis.get("themeAnchors") or []
    anchors = sorted({i for i in explicit if type(i) is int and 0 <= i < count})
    if anchors or not count:
        return anchors
    # Link recurring openings by transposition-invariant intervals. Singletons
    # remain ordinary phrases, available to the performer in the full source.
    groups = {}
    for index, phrase in enumerate(analysis.get("phrases") or []):
        pitches = phrase.get("anchorPitches", phrase.get("openingPitches", [])) if isinstance(phrase, dict) else []
        if isinstance(pitches, list) and len(pitches) >= 4 and all(type(n) is int for n in pitches[:4]):
            intervals = tuple(b - a for a, b in zip(pitches[:3], pitches[1:4]))
            if any(intervals):
                groups.setdefault(intervals, []).append(index)
    return sorted({0} | {i for matches in groups.values() if len(matches) > 1 for i in matches})


def _marked(text):
    _, programs, match = _catalog()
    # Match full GM names first. Steel Drums and Synth Drum are pitched patches.
    def mark(found):
        name = found.group().casefold()
        # A bare patch name inside a hyphenated compound is not necessarily a
        # player (e.g. a descriptor ending in "-like"). Explicit role suffixes are.
        tail = found.string[found.end():]
        if re.match(r"-[a-z]", tail) and not re.match(r"-(?:led|played|driven|and)\b", tail):
            return found.group()
        return f" @{KIT if name == 'drums' else programs[name]}@ "
    words = text.casefold().replace("@", " ")
    terms = r"\b(?:" + "|".join(re.escape(k) for k in sorted(INSTRUMENT_TERMS, key=len, reverse=True)) + r")\b"
    words = re.sub(terms, lambda m: f" @{INSTRUMENT_TERMS[m.group()]}@ ", words)
    marked = match.sub(mark, words)
    marked = DRUMS.sub(f" @{KIT}@ ", marked)
    return re.sub(r"\s+", " ", marked).strip()


def _members(text):
    names = [int(x) for x in re.findall(r"@(-?\d+)@", _marked(text))]
    return list(dict.fromkeys(names))


def _stated_leads(text):
    marked = _marked(text)
    roles = _role_names(marked)
    roles.update(int(m.group(1)) for m in re.finditer(r"@(\d+)@\s+(?:(?:main|lead|singing)\s+)?(?:melody|lead|theme|tune|hook)\b", marked))
    return roles


def _part_words(marked, program):
    # Keep modifiers local to their instrument. "Pulsing bass and brushed drums"
    # gives two different performance instructions, even within the same clause.
    result = []
    for clause in re.split(r"[,;.!?]|\b(?:and|with|over|above|behind|plus|while)\b", marked):
        if set(re.findall(r"@(-?\d+)@", clause)) == {str(program)}:
            result.append(clause)
    return " ".join(result)


def _phrase_part(director, role, direction):
    program = KIT if role["kind"] == "percussion" else role["program"]
    # Keep coordinated verbs attached to their player ("piano plays the theme
    # and answers with chords"). Start a new subject with each named instrument.
    fragments = []
    for sentence in re.split(r"[,;.!?]", direction.casefold()):
        players = set()
        for clause in re.split(r"\b(?:and|with|over|above|behind|plus|while)\b", sentence):
            players = set(_members(clause)) or players
            if players == {program}:
                fragments.append(clause)
    words = " ".join(fragments)
    if re.search(r"\b(?:answer\w*|respond\w*|repl(?:y|ies)|trad(?:e|ing)|fill(?:s|ing)?|"
                 r"build(?:s|ing)?|leave space|hold back)\b", words):
        return True
    if re.search(r"\b(?:stead\w*|continuous\w*|throughout|unbroken|ostinat[oi]|walking|"
                 r"puls(?:e|ing)|backbeat|ride cymbal|dron(?:e|ing)|repeating)\b", words):
        return False
    player = "drum kit" if program == KIT else _catalog()[0][program]
    choice = director.choose(
        f"Should the {player} {role['kind']} part follow the theme's phrases or maintain its written "
        f"{role['gesture']} figure? Use the listener's assignment to this player. Another player can "
        "answer while this one keeps playing.",
        {"follow": "leave room, answer the lead or build on its return", "maintain": "keep its figure through the phrase"})
    return choice == "follow"


def _part_kind(program, words):
    if re.search(r"\b(?:chords?|comping|voicings?)\b", words):
        return "chords"
    if re.search(r"\b(?:arpeggios?|arpeggiat\w*|broken chords?)\b", words):
        return "arpeggio"
    if re.search(r"\b(?:pedal|dron\w*)\b", words):
        return "pedal"
    if re.search(r"\b(?:countermelody|counterline|responds?|answers?)\b", words):
        return "counterline"
    if program in range(32, 40) or re.search(r"\b(?:bassline|walking bass|bass line)\b", words):
        return "bass"
    return None


def _excluded_player(program, direction):
    for clause in re.split(r"[,;.!?]|\bbut\b", direction, flags=re.I):
        negative = re.search(r"\b(?:no|without|omit|remove|drop|avoid|instead of)\s+", clause, re.I)
        if negative and program in _members(clause[negative.end():]):
            return True
    return program != KIT and _excluded(program, direction)


def _score_players(director, direction, old):
    names = _catalog()[0]
    named = [p for p in _members(direction) if not _excluded_player(p, direction)]
    explicit = _explicit(direction)
    solo = _size_hint(direction) is True
    old_players = [] if not old else [old["leadProgram"]] + [KIT if r["kind"] == "percussion" else r["program"] for r in old["roles"]]
    edit = None
    if old and not solo:
        edit = director.choose("How is the listener changing the existing players?",
                               {"replace": "replace or recast the group", "add": "add performers while keeping the group",
                                "remove": "remove performers while keeping the rest", "roles": "same performers, new roles"})
    if (edit in ("add", "remove", "roles") and named) or edit == "remove":
        players = list(dict.fromkeys(p for p in old_players + named if not _excluded_player(p, direction)))
    elif solo and len(named) == 1:
        players = named
    else:
        # Free instrumental proposals allow an unfamiliar direction to choose any GM player.
        answer = director.write("Name the 1 to 4 instrumental performers in the finished arrangement, melody player first. "
                                "Obey explicit instrumentation, omissions, and additions to the current group. "
                                "Only a comma-separated list of common instrument names. A drum kit counts as one player.", 48)
        proposed = [p for p in _members(answer) if not _excluded_player(p, direction)]
        # A fully specified cast does not need the model to supply extra names.
        exact = len(named) >= 2 and not old and not re.search(r"\b(?:add|including|plus others|among others)\b", direction, re.I)
        players = named if exact else list(dict.fromkeys(named + proposed))
    if not players and old_players:
        players = [p for p in dict.fromkeys(old_players) if not _excluded_player(p, direction)]
    melodic = [p for p in players if p != KIT]
    if not melodic:
        families = {i: names[i * 8] + " to " + names[i * 8 + 7] for i in range(16)}
        family = director.choose("Which instrument family carries the source tune?", families)
        allowed = {p: names[p] for p in range(family * 8, family * 8 + 8) if not _excluded_player(p, direction)}
        if not allowed:
            raise ValueError("Choose an instrument that can carry the source melody.")
        melodic = [director.choose("Which instrument in that family plays the main tune?", allowed)]
    stated_leads = _stated_leads(direction)
    if edit in ("add", "remove") and old["leadProgram"] in melodic and not stated_leads.intersection(melodic):
        lead = old["leadProgram"]
    elif len(stated_leads.intersection(melodic)) == 1:
        lead = next(iter(stated_leads.intersection(melodic)))
    elif explicit and explicit[0] in melodic:
        lead = explicit[0]
    else:
        lead = director.choose("Which listed player carries the recognizable main tune?", {p: names[p] for p in melodic[:12]})
    if solo:
        players = [lead]
    remaining = [p for p in players if p != lead][:3]
    cast = []
    # A pianist, guitarist or other polyphonic lead can accompany their own tune.
    # Avoid manufacturing a second performer in a solo.
    existing = {} if not old or edit not in ("add", "remove") else {r["program"]: r["kind"] for r in old["roles"]}
    if lead == (old or {}).get("leadProgram") and edit in ("add", "remove"):
        if lead in existing:
            cast.append((existing[lead], lead))
    elif lead in POLYPHONIC:
        self_part = director.choose(f"How does the melody player ({names[lead]}) accompany their own melody? "
                                    "Allow a second-hand part in a solo or comping when appropriate.",
                                    {"none": "melody only", "chords": "chord voicings", "arpeggio": "broken chords", "pedal": "pedal notes"})
        if self_part != "none":
            cast.append((self_part, lead))
    for p in remaining:
        kind = "percussion" if p == KIT else _part_kind(p, _part_words(_marked(direction), p)) or existing.get(p)
        if kind is None:
            kind = director.choose(f"What supporting part does {names[p]} play?", KINDS)
        cast.append((kind, p))
    return lead, cast


def _event(beat, duration, degree, velocity, pitch=None):
    note = {"beat": round(beat, 4), "duration": round(duration, 4), "degree": degree, "velocity": velocity}
    if pitch is not None:
        note["pitch"] = pitch
    return note


def _pattern(kind, gesture, meter):
    """Realize the selected one-bar gesture in any supported meter, leaving its written rests."""
    if kind == "percussion":
        events = []
        for i in range(meter):
            if gesture == "ride":
                events.append(_event(i, .18, 0, 67 if i % 2 == 0 else 74, 51))
                if i % 2:
                    events.extend([_event(i, .12, 0, 58, 44), _event(i + .5, .12, 0, 54, 51)])
            elif gesture == "backbeat":
                events.extend([_event(i, .14, 0, 78, 36 if i % 2 == 0 else 38),
                               _event(i + .5, .11, 0, 48, 42)])
            elif gesture == "brush":
                events.append(_event(i, .25, 0, 48 if i % 2 == 0 else 62, 38))
                if i % 2:
                    events.append(_event(i + .5, .1, 0, 40, 42))
            elif gesture == "hand":
                events.append(_event(i + (.5 if i % 2 else 0), .18, 0, 68 if i % 2 else 75, 63 if i % 2 else 64))
            elif i == 0 or (i > 1 and i == meter - 1):
                events.append(_event(i, .2, 0, 59, 41))
        return events
    if gesture == "hold":
        offsets = [0.]
        lengths = [meter * .94]
    elif gesture == "two":
        offsets = [float(i) for i in range(0, meter, 2)]
        lengths = [1.65] * len(offsets)
    elif gesture == "backbeats":
        offsets = [float(i) for i in range(1, meter, 2)]
        lengths = [.42] * len(offsets)
    elif gesture == "anticipate":
        offsets = sorted({.5, max(1, meter - 2), meter - .5})
        lengths = [.4] * len(offsets)
    elif gesture == "offbeat":
        offsets = [i + .5 for i in range(meter)]
        lengths = [.35] * len(offsets)
    elif gesture == "answer":
        offsets = [meter - 1.5, meter - 1., meter - .5]
        lengths = [.4, .4, .45]
    elif gesture == "wave":
        offsets = [i / 2 for i in range(meter * 2)]
        lengths = [.45] * len(offsets)
    else:
        offsets = list(range(meter))
        lengths = [0.89 if gesture == "walk" else .62] * meter
    degrees = (0,) if kind in ("pedal", "chords") or (kind == "bass" and gesture == "pulse") else (0, 2) if gesture == "two" else (0, 1, 2, 3) if gesture == "walk" else (0, 1, 2, 1)
    return [_event(t, min(length, meter - t), degrees[i % len(degrees)], 74 if i == 0 else 63 + 3 * (i % 3))
            for i, (t, length) in enumerate(zip(offsets, lengths))]


def _roles(director, cast, meter, direction):
    roles = []
    names = _catalog()[0]
    for kind, program in cast:
        player = "drum kit" if kind == "percussion" else names[program]
        words = _part_words(_marked(direction), program)
        gestures = {"pulse": r"\b(?:pulse|pulsing|repeated)\b", "walk": r"\bwalking\b",
                    "backbeat": r"\bbackbeats?\b", "ride": r"\bride cymbal\b",
                    "hold": r"\b(?:sustained|held)\b", "offbeat": r"\boffbeats?\b"}
        gesture = next((g for g, pattern in gestures.items() if g in GESTURES[kind] and re.search(pattern, words)), None)
        if gesture is None:
            gesture = director.choose(f"Choose the repeating {kind} figure for {player}. What does the direction sound like?",
                                      GESTURES[kind])
        role = {"kind": kind, "program": None if kind == "percussion" else program,
                "gesture": gesture, "pattern": _pattern(kind, gesture, meter)}
        if kind == "percussion":
            if re.search(r"\b(?:tr[ -]?)?808\b", direction, re.I):
                role["kit"] = 25
            elif re.search(r"\b(?:drum machine|electronic (?:kit|drums?|percussion)|programmed drums?)\b", direction, re.I):
                role["kit"] = 24
            elif re.search(r"\bbrush(?:es|ed)?\b", direction, re.I) or gesture == "brush":
                role["kit"] = 40
            else:
                role["kit"] = 0
        roles.append(role)
    return roles


def _changes(director, direction):
    axes = {"revoice": "change only the instrument that plays the existing lead melody",
            "players": "instruments / lineup only", "pulse": "speed only", "groove": "meter / rhythm or groove only",
            "phrasing": "lead articulation or timing only", "harmony": "chords or harmonic color only",
            "interaction": "when the accompanists hold back, answer the lead, or build at a returning theme",
            "dynamics": "intensity / room ambience only", "form": "opening, ending or form only",
            "production": "sound treatment or studio effects only",
            "feel": "performance feel or mood with same players", "all": "entire new musical arrangement or style",
            "several": "specific changes to two or more of the above"}
    axis = director.choose("What is the listener asking to change in the selected arrangement? "
                           "Keep unmentioned decisions on a revision.", axes)
    if axis == "all":
        return set(GROUPS)
    if axis == "feel":
        scope = director.choose(
            f"For this mood edit, which part may change? Listener's words: «{direction}». "
            "If they like the backing or want the beat to stay, have the melody player carry the change.",
            {"lead": "rephrase the tune over the existing performance",
             "ensemble": "reshape the pace and intensity of the whole ensemble"})
        return {"phrasing"} if scope == "lead" else {"pulse", "phrasing", "dynamics"}
    if axis == "several":
        return {group for group in GROUPS if director.choose(f"Did the listener request a change to {axes[group]}?",
                                                              {False: "keep the current decision", True: "change it"})}
    return {axis}


def _named_tempo(direction):
    named = re.search(r"\b(\d{2,3}(?:\.\d+)?)\s*(?:bpm|beats per minute)\b|\bbpm\s*[:=]?\s*(\d{2,3}(?:\.\d+)?)\b", direction, re.I)
    if named:
        value = float(named.group(1) or named.group(2))
        if not _bounded_number(value, 40, 240):
            raise ValueError("Choose a tempo between 40 and 240 BPM.")
        return value
    return None


def _tempo(director, analysis, old, direction):
    named = _named_tempo(direction)
    if named is not None:
        return named
    reference = old.get("bpm") if old else analysis.get("bpm")
    named = _named_tempo(director.brief)
    if named is not None:
        return named
    tempos = {56: "very slow and spacious", 72: "gentle, unhurried", 88: "relaxed walking pace",
              104: "moderate", 116: "lilting medium pulse", 132: "brisk", 154: "fast", 180: "driving and fast"}
    if _bounded_number(reference, 40, 240):
        tempos[round(max(40, reference * .83))] = "a little slower than the current pulse"
        tempos[round(min(240, reference * 1.18))] = "a little quicker than the current pulse"
        tempos[round(reference)] = "retain the current pulse"
    return director.choose("Choose a quarter-note tempo (BPM) for the desired performance.",
                           {n: f"{n} BPM, {m}" for n, m in sorted(tempos.items())})


def _meter(text):
    matches = re.findall(r"(?<!\d)([23456])\s*/\s*4(?!\d)", text)
    if len(set(matches)) == 1:
        return int(matches[0])
    if re.search(r"\bcommon time\b", text, re.I):
        return 4
    return None


def _subdivision(text):
    terms = {"straight": r"\b(?:straight|even|unswung) (?:time|feel|subdivisions?|eighths?|quavers?)\b",
             "swing": r"\b(?:swing|swung|swinging|shuffle[ds]?)\b",
             "triplet": r"\btriplets?\b"}
    found = [key for key, pattern in terms.items() if re.search(pattern, text, re.I)]
    return found[0] if len(found) == 1 else None


def _lead_touch(director, direction, phrasing, old):
    """Write dynamics and articulation the melody player can perform within each source phrase."""
    prior = (old or {}).get("leadTouch")
    notation = director.write(
        f"Write the lead player's expression for «{direction}» with {phrasing} phrasing. "
        f"Previous expression: {prior or 'regular accents and note lengths'}. "
        "Return just a JSON array of five integers: MIDI velocity of the opening note, the middle, "
        "and the last note of a phrase (36 to 112, 80 is moderate); note length as a percentage "
        "(55 to 115, 100 retains the written length); and how many milliseconds the last attack leans "
        "ahead of or behind the pulse (-60 to 60, 0 is on time). Choose values the listener could hear. "
        "The backing sets its own pace.", 64)
    try:
        marks = json.loads(notation.strip().removeprefix("```json").removeprefix("```").removesuffix("```").strip())
    except ValueError:
        marks = None
    bounds = ((36, 112), (36, 112), (36, 112), (55, 115), (-60, 60))
    if not (isinstance(marks, list) and len(marks) == len(bounds)
            and all(type(n) is int and lo <= n <= hi for n, (lo, hi) in zip(marks, bounds))):
        # Compact models can give performance prose. Ask for playable marks using constrained decoding.
        levels = {80: "mezzo forte", 48: "piano", 64: "mezzo piano", 100: "forte"}
        marks = [director.choose(f"Choose the lead note's dynamic at the {part} of the phrase.", levels)
                 for part in ("opening", "middle", "end")]
        marks.extend([100, 0])
    return {"velocity": marks[:3], "lengthPercent": marks[3], "endOffsetMs": marks[4]}


def _arrange(analysis, direction, old, director):
    changes = _changes(director, direction) if old else set(GROUPS)
    plan = copy.deepcopy(old) if old else {"version": 1}
    plan.setdefault("realization", "score")
    plan["themeAnchors"] = _anchors(analysis)
    if "production" in changes:
        plan["realization"] = director.choose(
            f"How must the listener's own request be played? «{direction}» "
            "Use score for playable parts, including synthesizers, keyboards, acoustic players and drum machines. "
            "Only use produced if the listener asked for an audio treatment or sound the instruments cannot play. "
            "Ignore production details added by the arranger.",
            {"score": "direct instrumental performance", "produced": "requested audio treatment or novel sound design"})
    if "pulse" in changes:
        plan["bpm"] = _tempo(director, analysis, old, direction)
    if "groove" in changes:
        plan["meter"] = _meter(direction) or _meter(director.brief) or director.choose("How many beats belong in one measure?", METERS)
        plan["subdivision"] = _subdivision(direction) or _subdivision(director.brief) or director.choose(
            "How should the players subdivide the pulse?", SUBDIVISIONS)
    if "phrasing" in changes:
        plan["phrasing"] = director.choose("How should the lead rephrase the source motif?", PHRASINGS)
        plan["leadTouch"] = _lead_touch(director, direction, plan["phrasing"], old)
    if "harmony" in changes:
        plan["harmony"] = director.choose("How should the accompanists voice the source harmonies?", HARMONIES)
    if "dynamics" in changes:
        plan["phraseDynamics"] = director.choose("How should intensity develop across phrases?", DYNAMICS)
        plan["room"] = director.choose("What sense of acoustic space suits the performance?", ROOMS)
    if "form" in changes:
        plan["introBars"] = director.choose("How many bars of introduction before the theme?",
                                            {0: "start immediately with the tune", 1: "short one-bar pickup", 2: "two-bar introduction"})
        plan["endingBars"] = director.choose("How many additional bars after the last source phrase?",
                                              {0: "close on the final phrase", 1: "one-bar cadence", 2: "two-bar coda"})
    revoice = (changes == {"players"} and len(_members(direction)) == 1
               and re.search(r"\b(?:lead|tune|melody|hook|theme)\b", direction, re.I))
    if changes == {"revoice"} or revoice:
        named = [p for p in _members(direction) if p != KIT and not _excluded_player(p, direction)]
        proposed = [p for p in _members(director.brief) if p != KIT and not _excluded_player(p, direction)]
        candidates = named or proposed
        if not candidates:
            raise ValueError("Which instrument should carry the tune in this take?")
        names = _catalog()[0]
        plan["leadProgram"] = director.choose("Which performer is the new melody player?", {p: names[p] for p in candidates})
        return plan
    if old and changes == {"phrasing"} and "backingTiming" not in plan:
        responsive = old.get("phraseInteraction", "steady") != "steady"
        if any(r["kind"] == "counterline" or (responsive and r.get("followPhrases", True)) for r in old["roles"]):
            # These players listened to the previous lead to place notes in its rests.
            # Keep the cue they heard across further revisions of the lead.
            plan["backingTiming"] = {key: copy.deepcopy(old[key]) for key in ("phrasing", "leadTouch") if key in old}
    elif changes.intersection({"players", "groove", "interaction"}) or ("phrasing" in changes and len(changes) > 1):
        plan.pop("backingTiming", None)
    if "players" in changes:
        plan["leadProgram"], cast = _score_players(director, direction, old)
    elif "groove" in changes:
        cast = [(r["kind"], KIT if r["kind"] == "percussion" else r["program"]) for r in plan["roles"]]
    if changes.intersection({"players", "groove"}):
        plan["roles"] = _roles(director, cast, plan["meter"], direction)
        if old and "groove" not in changes:
            prior_roles = {(r["kind"], r["program"]): r for r in old["roles"]}
            plan["roles"] = [copy.deepcopy(prior_roles.get((r["kind"], r["program"]), r)) for r in plan["roles"]]
    if "interaction" in changes and plan["roles"]:
        plan["phraseInteraction"] = director.choose(
            "How should the backing respond to the recorded phrases? Keep a repeating figure for a continuous pulse. "
            "Let the players trade space when the direction calls for an answer or a fuller theme return.", INTERACTIONS)
        plan["phraseInteractionVersion"] = 2
    if plan.get("phraseInteraction", "steady") != "steady" and changes.intersection({"players", "groove", "interaction"}):
        prior_roles = {(r["kind"], r["program"]): r for r in old["roles"]} if old else {}
        for role in plan["roles"]:
            prior = prior_roles.get((role["kind"], role["program"]))
            if prior is None or "interaction" in changes:
                role["followPhrases"] = _phrase_part(director, role, direction)
            elif "followPhrases" in prior:
                role["followPhrases"] = prior["followPhrases"]
    return plan


def _prior(analysis):
    plan = analysis.get("parentPlan")
    if not isinstance(plan, dict) or not plan:
        return None
    keys = ("version", "bpm", "meter", "subdivision", "phrasing", "harmony", "phraseDynamics",
            "introBars", "endingBars", "leadProgram", "roles")
    if any(k not in plan for k in keys) or plan["version"] != 1 or not isinstance(plan["roles"], list):
        raise ValueError("The selected take has an unsupported arrangement document.")
    return plan


def director_weights():
    installer = json.loads((HERE / "score-director-assets.json").read_text())
    directory = HOME / "score-director"
    try:
        receipt = json.loads((directory / ".djound-verified.json").read_text())
    except (OSError, ValueError):
        receipt = {}
    if (isinstance(receipt, dict) and all(receipt.get(k) == installer[k] for k in ("model", "revision"))
            and (directory / "model.safetensors").is_file()):
        return directory, installer, 4 * 1024**3
    compact = json.loads((HERE / "assets.json").read_text())
    directory = HOME / compact["modelDirectory"]
    if not (directory / "model.safetensors").is_file():
        raise RuntimeError("Install the local arrangement planner.")
    return directory, compact, 2 * 1024**3


class _Director:
    def __init__(self, context):
        import mlx.core as mx
        from mlx_lm import generate, load
        from mlx_lm.sample_utils import make_sampler

        weights, metadata, memory = director_weights()
        self.identity = metadata["model"] + "@" + metadata["revision"]
        mx.set_memory_limit(memory)
        mx.set_cache_limit(128 * 1024**2)
        self.model, self.tokenizer = load(str(weights), tokenizer_config={"trust_remote_code": False})
        self.generate, self.mx, self.greedy = generate, mx, make_sampler(temp=0)
        self.context = json.dumps(context, ensure_ascii=False, separators=(",", ":"))
        self.brief = self.write(
            "Write a practical chart for the requested music. Choose the tempo, meter, feel, instruments and each "
            "part's rhythm that make this direction idiomatic. Pick the destination pulse, even when different from the source. "
            "Start with one numeric target BPM, time signature and straight eighths, swung eighths or triplets. "
            "Then specify who plays the hook, what each accompanist plays, chord color, phrasing, and any requested effects. "
            "Keep melody pitches from the recording. Name a source key only when the source analysis supplies it. "
            "Respect explicitly named players and preserve unchanged choices in a revision. Write under 85 words.", 170)
        self.context += "\nArranger's rehearsal cue: " + self.brief

    def _answer(self, question, suffix, limit, sampler):
        system = ("You arrange a recognizable theme for real instrumental players. Follow the listener's latest direction. "
                  "The source facts and parent arrangement are context. Preserve choices not targeted by a revision. " + suffix)
        messages = [{"role": "system", "content": system},
                    {"role": "user", "content": self.context + "\n" + question}]
        prompt = self.tokenizer.apply_chat_template(messages, tokenize=False, add_generation_prompt=True, enable_thinking=False)
        return self.generate(self.model, self.tokenizer, prompt=prompt, max_tokens=limit, sampler=sampler,
                             prefill_step_size=128, verbose=False).strip()

    def write(self, question, limit):
        return self._answer(question, "Answer briefly.", limit, self.greedy)

    def choose(self, question, options):
        keys = list(options)
        if len(keys) == 1:
            return keys[0]
        labels = {}
        for key, description in options.items():
            if isinstance(key, str):
                word = key.replace("_", " ")
            elif type(key) is bool:
                word = "change" if key else "keep"
            else:
                word = description.split(",")[0]
            labels[word.casefold()] = key
        # Score meaningful answer words. A small instruction model can select the
        # first arbitrary A/B/C label regardless of the musical content.
        eos = self.tokenizer.eos_token_id
        paths = []
        for word in labels:
            for prefix in ("", " "):
                paths.append(self.tokenizer.encode(prefix + word, add_special_tokens=False) + [eos])
        depth = 0
        max_tokens = max(map(len, paths))
        def constrained(log_probs):
            nonlocal paths, depth
            if not paths:
                return self.mx.array([eos])
            allowed = self.mx.array(sorted({p[depth] for p in paths}))
            selected = allowed[self.mx.argmax(log_probs[:, allowed], axis=-1)]
            token = selected.item()
            paths = [p for p in paths if p[depth] == token and depth + 1 < len(p)]
            depth += 1
            return selected
        menu = "\n".join(f"{word}: {options[key]}" for word, key in labels.items())
        answer = self._answer(question + "\n" + menu, "Reply with the exact matching option name.", max_tokens, constrained).casefold()
        if answer not in labels:
            raise RuntimeError("The language planner could not resolve a musical choice.")
        return labels[answer]


def _run(request):
    analysis, direction = request["analysis"], request["direction"]
    old = _prior(analysis)
    source = request.get("sourceSnapshot") or _compact(analysis)
    context = {"source": source, "currentTake": request["parentCaption"],
               "listener": direction}
    if old:
        context["currentScore"] = {k: old[k] for k in ("bpm", "meter", "subdivision", "phrasing", "harmony",
                                                        "phraseDynamics", "introBars", "endingBars")}
        context["currentScore"]["phraseInteraction"] = old.get("phraseInteraction", "steady")
        if "leadTouch" in old:
            context["currentScore"]["leadTouch"] = old["leadTouch"]
        names = _catalog()[0]
        context["currentScore"]["players"] = [names[old["leadProgram"]]] + [
            f"{r['kind']}: {names[r['program']] if r['program'] is not None else 'drum kit'}" for r in old["roles"]]
    reconsider = bool(old and request.get("reconsider"))
    if reconsider:
        # Write the destination before showing the old band. Otherwise a vivid description of
        # a finished performance can convince the director it already fulfills a new purpose.
        director = _Director({"source": source, "listener": direction, "task": (
            "Imagine the performance the listener wants, using the recording's melody. "
            "Translate their intended listening experience into concrete tempo, texture, "
            "energy and instrumental parts. Write a chart that can deliver that experience.")})
        scope = director.choose(
            f"Read only this request: «{direction}». Is it a brief for a whole interpretation, "
            "or does the listener specify what to keep or which individual part or setting to change?",
            {"interpret": "a listening situation, overall sound or genre with the musical choices left to the performers",
             "targeted": "a specific instrument, part, tempo, or edit relative to something the listener wants to keep"})
        if scope == "interpret":
            old = None
        else:
            director.context += "\nSelected take for the targeted edit: " + json.dumps(
                {"description": context["currentTake"], "score": context["currentScore"]}, ensure_ascii=False)
            if director.choose(f"Does the selected take already fulfill the exact instruction «{direction}»?",
                               {"change": "there is a requested musical change still to make",
                                "satisfied": "the named setting is already present and no change was requested"}) == "satisfied":
                return None
    else:
        director = _Director(context)
    plan = _arrange(analysis, direction, old, director)
    plan["conductorCue"] = " ".join(director.brief.split())[:1400]
    plan["director"] = director.identity
    return plan


def plan_arrangement(analysis: dict, direction: str, parent_caption: str = "", *, deadline: float | None = None,
                     reconsider: bool = False) -> dict | None:
    """Return a v1 score. A short-lived local model releases its memory before audio rendering."""
    if not isinstance(direction, str) or not direction.strip() or len(direction) > 4000:
        raise ValueError("Describe the desired arrangement in up to 4000 characters.")
    if not isinstance(analysis, dict) or not isinstance(parent_caption, str):
        raise ValueError("Provide the recording analysis and its selected take description.")
    compact = _compact(analysis)
    if not compact["phraseCount"]:
        raise ValueError("The recording needs at least one identifiable phrase to arrange.")
    # Pass phrase indices and compact source summaries only; a full transcription
    # can contain thousands of notes and does not belong in the language context.
    retained = {"bpm": analysis.get("bpm"), "_phraseCount": compact["phraseCount"], "themeAnchors": _anchors(analysis)}
    if _prior(analysis):
        retained["parentPlan"] = analysis["parentPlan"]
    seconds = 120 if deadline is None else min(120, deadline - time.monotonic())
    if not math.isfinite(seconds) or seconds <= 0:
        raise TimeoutError("The arrangement planner exceeded its deadline.")
    request = {"analysis": retained, "sourceSnapshot": compact, "direction": direction.strip(),
               "parentCaption": parent_caption.strip()[:1800]}
    if reconsider:
        request["reconsider"] = True
    try:
        proc = subprocess.run([sys.executable, "-B", str(Path(__file__).resolve())], text=True,
                              input=json.dumps(request, allow_nan=False), capture_output=True, timeout=seconds,
                              env={**os.environ, "HF_HUB_OFFLINE": "1", "TRANSFORMERS_OFFLINE": "1",
                                   "TOKENIZERS_PARALLELISM": "false"})
    except subprocess.TimeoutExpired:
        raise TimeoutError("The arrangement planner exceeded its deadline.") from None
    if proc.returncode:
        raise RuntimeError("The local language planner could not arrange the recording.")
    result = json.loads(proc.stdout)
    if reconsider and result is None:
        return None
    if "error" in result:
        raise ValueError(result["error"])
    return result


if __name__ == "__main__":
    try:
        print(json.dumps(_run(json.load(sys.stdin)), allow_nan=False))
    except ValueError as exc:
        print(json.dumps({"error": str(exc)}))
